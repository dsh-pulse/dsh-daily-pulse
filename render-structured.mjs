#!/usr/bin/env node
/**
 * render-structured.mjs — M3 · data-mode="structured"（设计系统 v0.2 §11）
 *
 * 产出"干净英文正文 + JSON-LD"，专供 AI 引擎（ChatGPT / Gemini）引用，对应 GEO 战略
 * （README「英文版 = AI 天然引用源」）。该模式不挂装饰、不混排，保证机器可读。
 *
 * 输出（reports/structured/，随 daily.yml 的 `git add reports` 一并提交）：
 *   structured/latest.json        最新一期 JSON-LD（Dataset schema + 全量快照字段）
 *   structured/latest.md          最新一期干净英文正文（data-led，供 AI 直接引用）
 *   structured/<期号>.json        全部历史期号 JSON-LD（档案馆时间线机器读取）
 *
 * 依赖 tokens.mjs（cst / fmtNum）；运行：node render-structured.mjs
 * （放在 render.mjs 之后、commit 之前；也可被 render.mjs import 复用 JSON-LD 构造）
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import { fmtNum, cst } from './tokens.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const STORE = join(__dirname, 'store');
const REPORTS = join(__dirname, 'reports');
const OUT = join(REPORTS, 'structured');
mkdirSync(OUT, { recursive: true });

// 站点根 URL（GitHub Pages）。本地可 DSH_SITE_URL 覆盖；默认按 remote 仓库推断。
const SITE_URL = process.env.DSH_SITE_URL || 'https://dsh-pulse.github.io/dsh-daily-pulse/';

/**
 * 构造一期快照的 JSON-LD（Dataset schema，机器可读；含全部快照字段，AI 可直接消费）。
 * @param {object} snap   单期快照对象（latest.json 结构）
 * @param {number} issueNo 期号（1 起）
 */
export function buildDatasetJsonLd(snap, issueNo) {
  const k = snap.kpis || {};
  const h = snap.health || {};
  const no = String(issueNo).padStart(4, '0');
  const page = `${SITE_URL}latest.html`;
  const dataUrl = `${SITE_URL}structured/${no}.json`;

  const measured = [
    ['Total plugins (topic count, incl. forks)', k.total_plugins],
    ['Tracked plugins (non-fork)', k.non_fork_plugins],
    ['New repos in 8h', k.new_8h_repos],
    ['Official repo stars', k.official_stars],
    ['Official repo forks', k.official_forks],
    ['npm weekly downloads (@deepseek-ai/dsh)', k.npm_weekly_downloads],
    ['Official stars delta (8h)', k.delta_8h_stars],
    ['Ecosystem health score', h.score],
    ['Stale repos (7d no push)', h.stale_7d],
    ['Stale repos (24h no push)', h.stale_1d],
  ]
    .filter(([, v]) => v != null)
    .map(([name, value]) => ({ '@type': 'PropertyValue', name, value }));

  return {
    '@context': [
      'https://schema.org',
      { dsh: 'https://dsh-pulse.github.io/dsh-daily-pulse/ns#' },
    ],
    '@type': 'Dataset',
    '@id': dataUrl,
    name: `DSH Plugin Ecosystem Snapshot · Issue #${issueNo}`,
    description: `Daily snapshot of the DeepSeek Harness (DSH) plugin ecosystem: ${k.total_plugins} plugins total, +${k.new_8h_repos} in 8h, official repo ${k.official_stars} stars, npm weekly ${fmtNum(k.npm_weekly_downloads)}.`,
    url: page,
    datePublished: snap.generated_at,
    dateModified: snap.generated_at,
    temporalCoverage: `${snap.window_start}/${snap.window_end}`,
    inLanguage: 'en',
    publisher: { '@type': 'Organization', name: 'dsh-pulse', url: SITE_URL },
    creator: { '@type': 'Organization', name: 'dsh-daily-pulse' },
    distribution: { '@type': 'DataDownload', contentUrl: dataUrl, encodingFormat: 'application/json' },
    variableMeasured: measured,
    // —— 以下为快照本体（JSON-LD 解析器忽略未知字段，AI 可直接读）——
    kpis: k,
    official: snap.official || null,
    leaderboard: (snap.leaderboard || []).map((r) => ({
      rank: r.rank, name: r.name, stars: r.stars, delta: r.delta,
      category: r.category, score: r.score, url: r.url, created: r.created, pushed: r.pushed,
    })),
    growth: (snap.growth || []).map((r) => ({ rank: r.rank, name: r.name, delta: r.delta, stars: r.stars })),
    official_activity: snap.official_activity || [],
    health: h,
    summary: snap.summary ? { en: snap.summary.en, zh: snap.summary.zh } : null,
  };
}

/** 生成一期"干净英文正文"（data-led，无装饰、无混排，供 AI 引用 / GEO）。 */
export function buildEnglishMarkdown(snap, issueNo) {
  const k = snap.kpis || {};
  const h = snap.health || {};
  const lb = snap.leaderboard || [];
  const gr = snap.growth || [];
  const act = snap.official_activity || [];
  const sm = snap.summary || {};
  const num = (v) => (v == null ? '—' : Number(v).toLocaleString('en-US'));
  const CAT_EN = { 视觉: 'Vision/UI', 工作流: 'Workflow', 终端: 'Terminal', 其他: 'Other' };
  const FACTOR_EN = { 活跃度: 'Activity', 新鲜度: 'Freshness', 采用度: 'Adoption', 多样性: 'Diversity' };

  const lines = [];
  lines.push(`# DSH Ecosystem Pulse — Issue #${issueNo}`);
  lines.push('');
  lines.push(`Published ${cst(snap.generated_at)} (GMT+8) · Collection window ${cst(snap.window_start)} → ${cst(snap.window_end)}.`);
  lines.push('Sources: GitHub API (Search / topics / REST) + npm registry. Generated by dsh-daily-pulse.');
  lines.push('');

  lines.push('## Snapshot KPIs');
  lines.push(`- Total plugins (topic count, incl. forks): ${num(k.total_plugins)}`);
  lines.push(`- Tracked plugins (non-fork): ${num(k.non_fork_plugins)}`);
  lines.push(`- New repos in 8h: +${num(k.new_8h_repos)}`);
  lines.push(`- Official repo stars: ${num(k.official_stars)} · forks: ${num(k.official_forks)}`);
  lines.push(`- npm weekly downloads (@deepseek-ai/dsh): ${num(k.npm_weekly_downloads)}`);
  if (k.delta_8h_stars != null) lines.push(`- Official stars delta (8h): +${num(k.delta_8h_stars)}`);
  lines.push('');

  const table = gr.length ? gr : lb;
  if (table.length) {
    lines.push(`## ${gr.length ? 'Star growth leaderboard' : 'Rookie leaderboard'} (Top ${table.length})`);
    lines.push('');
    lines.push('| Rank | Repo | Δ stars | Total stars | Category |');
    lines.push('|---|---|---|---|---|');
    for (const r of table) {
      const gain = r.delta != null ? `+${num(r.delta)}` : `+${num(r.stars)}`;
      lines.push(`| ${r.rank} | ${r.name} | ${gain} | ${num(r.stars)} | ${CAT_EN[r.category] || 'Other'} |`);
    }
    lines.push('');
  }

  if (act.length) {
    lines.push('## Official activity (deepseek-ai/deepseek-harness)');
    for (const c of act) lines.push(`- \`${c.sha}\` ${c.msg}`);
    lines.push('');
  }

  lines.push('## Ecosystem health');
  lines.push(`- Health score: ${h.score}/100`);
  if (h.factors) {
    for (const f of Object.values(h.factors)) {
      lines.push(`  - ${FACTOR_EN[f.label] || f.label}: ${f.score}/${f.max}`);
    }
  }
  lines.push(`- Stale repos (7d no push): ${num(h.stale_7d)} of ${num(h.total_tracked)} tracked`);
  lines.push(`- Stale repos (24h no push): ${num(h.stale_1d)}`);
  lines.push('');

  if (sm.en) {
    lines.push('## Summary');
    lines.push(sm.en.replace(/<[^>]+>/g, ''));
    lines.push('');
  }
  return lines.join('\n');
}

function readSnapshots() {
  const raw = readFileSync(join(STORE, 'snapshots.jsonl'), 'utf8').trim().split('\n').filter(Boolean);
  return raw.map((l) => { try { return JSON.parse(l); } catch { return null; } }).filter(Boolean)
    .sort((a, b) => new Date(a.generated_at) - new Date(b.generated_at));
}

// 最新一期优先用 store/latest.json（summarize.mjs 的 AI 摘要只写回这里），
// 历史期从 snapshots.jsonl 读取；latest.json 缺失时回退快照最后一行。
function readLatest(snaps) {
  try {
    const l = JSON.parse(readFileSync(join(STORE, 'latest.json'), 'utf8'));
    if (l && l.generated_at) return l;
  } catch {}
  return snaps[snaps.length - 1] || null;
}

async function main() {
  const snaps = readSnapshots();
  if (snaps.length === 0) {
    console.error('[render-structured] store/snapshots.jsonl 为空，无法生成结构化输出');
    process.exit(1);
  }

  // 1) 全量历史期号 JSON-LD（档案馆时间线机器读取）
  snaps.forEach((s, i) => {
    const no = i + 1;
    const ld = buildDatasetJsonLd(s, no);
    writeFileSync(join(OUT, `${String(no).padStart(4, '0')}.json`), JSON.stringify(ld, null, 2) + '\n');
  });

  // 2) 最新一期：latest.json（JSON-LD）+ latest.md（干净英文正文）
  const latest = readLatest(snaps);
  const latestNo = snaps.length;
  writeFileSync(join(OUT, 'latest.json'), JSON.stringify(buildDatasetJsonLd(latest, latestNo), null, 2) + '\n');
  writeFileSync(join(OUT, 'latest.md'), buildEnglishMarkdown(latest, latestNo));

  console.log(`[render-structured] 已生成 reports/structured/（${snaps.length} 期 JSON-LD + latest.md）`);
  console.log(`  最新: structured/latest.json + structured/latest.md (Issue #${latestNo})`);
}

// 仅作为 CLI 直接运行时执行 main；被 render.mjs import 复用函数时不触发
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((e) => { console.error('[render-structured] 失败:', e); process.exit(1); });
}
